import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import postcss from 'postcss'
import tailwindcss from '@tailwindcss/postcss'
import { build } from 'esbuild'

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const cssPath = path.join(appRoot, 'components', 'focus', 'chatgpt-widget.css')
const entryPath = path.join(appRoot, 'components', 'focus', 'chatgpt-widget.entry.tsx')
const generatedPath = path.join(appRoot, 'lib', 'workforce-tools', 'mcp', 'focus-widget-resource.ts')

const [cssSource, javascript] = await Promise.all([
  readFile(cssPath, 'utf8').then(async (source) => {
    const result = await postcss([tailwindcss()]).process(source, { from: cssPath })
    return result.css
  }),
  build({
    entryPoints: [entryPath],
    bundle: true,
    write: false,
    outdir: path.join(appRoot, '.mcp-focus-widget-build'),
    format: 'iife',
    platform: 'browser',
    target: ['es2022'],
    minify: true,
    define: { 'process.env.NODE_ENV': '"production"' },
    logLevel: 'silent',
  }).then((result) => {
    const output = result.outputFiles.find((file) => file.path.endsWith('.js'))
    if (!output) throw new Error('FOCUS_WIDGET_JAVASCRIPT_MISSING')
    return output.text
  }),
])

const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="color-scheme" content="light dark"><title>LiquidHR Focus</title><style>${cssSource}</style></head><body><div id="root"></div><script>${javascript.replaceAll('</script', '<\\/script')}</script></body></html>`
await writeFile(generatedPath, `// Generated by scripts/build-chatgpt-focus-widget.mjs. Do not edit by hand.\nexport const CHATGPT_FOCUS_WIDGET_HTML = ${JSON.stringify(html)} as const\n`, 'utf8')
